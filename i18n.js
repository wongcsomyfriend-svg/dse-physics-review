    zh: s => {
      let m = s.match(/^(\(\d\)) only$/);
      if (m) return '只有 ' + m[1];
      m = s.match(/^(\(\d\)) and (\(\d\)) only$/);
      if (m) return '只有 ' + m[1] + ' 及 ' + m[2];
      m = s.match(/^(\(\d\)), (\(\d\)) and (\(\d\))$/);
      if (m) return m[1] + '、' + m[2] + ' 及 ' + m[3];
      return s;
    }
